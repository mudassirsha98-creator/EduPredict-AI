"""### 🛠️ Step 1: Data Preprocessing, Feature Engineering & Pipeline Creation
We will define clean preprocessing pipelines using scikit-learn. Categorical features will be encoded, and numerical features scaled. We will also save these pipelines for Streamlit integration.
"""

import numpy as np
import pandas as pd
import joblib
import os
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline

# Load the local dataset
data_path = '/content/student-mat.csv'
if os.path.exists(data_path):
    df = pd.read_csv(data_path, sep=';')
else:
    # Fallback to df in memory from previous cell
    pass

# Define feature groups (excluding G1 and G2 for early-warning predictive power)
numerical_cols = ['age', 'Medu', 'Fedu', 'traveltime', 'studytime', 'failures',
                  'famrel', 'freetime', 'goout', 'Dalc', 'Walc', 'health', 'absences']

categorical_cols = ['school', 'sex', 'address', 'famsize', 'Pstatus', 'Mjob', 'Fjob',
                     'reason', 'guardian', 'schoolsup', 'famsup', 'paid', 'activities',
                     'nursery', 'higher', 'internet', 'romantic']

# Create Preprocessing Pipeline
preprocessor = ColumnTransformer(
    transformers=[
        ('num', StandardScaler(), numerical_cols),
        ('cat', OneHotEncoder(handle_unknown='ignore', sparse_output=False), categorical_cols)
    ]
)

# Fit preprocessor to verify
X = df[numerical_cols + categorical_cols]
y_reg = df['G3']

# Define Risk Classes based on G3
def categorize_risk(g3):
    if g3 < 10:
        return 'High Risk'
    elif g3 <= 13:
        return 'Medium Risk'
    else:
        return 'Low Risk'

y_clf = y_reg.apply(categorize_risk)

# Split Data
X_train, X_test, y_train_reg, y_test_reg = train_test_split(X, y_reg, test_size=0.2, random_state=42)
_, _, y_train_clf, y_test_clf = train_test_split(X, y_clf, test_size=0.2, random_state=42, stratify=y_clf)

# Fit preprocessor on training data
X_train_preprocessed = preprocessor.fit_transform(X_train)
X_test_preprocessed = preprocessor.transform(X_test)

# Save the preprocessor
os.makedirs('edupredict_assets', exist_ok=True)
joblib.dump(preprocessor, 'edupredict_assets/preprocessor.joblib')
print("Preprocessing pipeline fitted and saved successfully.")

"""### 🤖 Step 2: Model Training (Regression and Classification)
We will train regression models to predict `G3` and a Random Forest Classifier to classify academic risk.
"""

from sklearn.ensemble import RandomForestRegressor, GradientBoostingRegressor, RandomForestClassifier
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, r2_score, classification_report, confusion_matrix

# --- Regression Models ---
reg_models = {
    'RandomForest': RandomForestRegressor(random_state=42, n_estimators=100),
    'GradientBoosting': GradientBoostingRegressor(random_state=42),
    'LinearRegression': LinearRegression()
}

best_reg_model = None
best_r2 = -float('inf')

for name, model in reg_models.items():
    model.fit(X_train_preprocessed, y_train_reg)
    preds = model.predict(X_test_preprocessed)
    r2 = r2_score(y_test_reg, preds)
    mae = mean_absolute_error(y_test_reg, preds)
    print(f"Regression [{name}]: R2 = {r2:.4f}, MAE = {mae:.4f}")
    if r2 > best_r2:
        best_r2 = r2
        best_reg_model = model

# Save best regression model
joblib.dump(best_reg_model, 'edupredict_assets/regressor.joblib')

# --- Classification Model (Academic Risk) ---
clf_model = RandomForestClassifier(random_state=42, n_estimators=150, class_weight='balanced')
clf_model.fit(X_train_preprocessed, y_train_clf)

clf_preds = clf_model.predict(X_test_preprocessed)
print("\n=== Classification Report for Academic Risk ===")
print(classification_report(y_test_clf, clf_preds))

# Save classification model
joblib.dump(clf_model, 'edupredict_assets/classifier.joblib')
print("Models saved successfully to 'edupredict_assets/' directory.")

"""### 🔍 Step 3: Explainable AI (Permutation Importance)
We will compute feature importance to display which features play the most significant role.
"""

from sklearn.inspection import permutation_importance

# Get feature names after one-hot encoding
ohe_feature_names = preprocessor.named_transformers_['cat'].get_feature_names_out(categorical_cols)
all_feature_names = list(numerical_cols) + list(ohe_feature_names)

# Compute Permutation Importance
result = permutation_importance(best_reg_model, X_test_preprocessed, y_test_reg, n_repeats=10, random_state=42)
importance_df = pd.DataFrame({
    'feature': all_feature_names,
    'importance': result.importances_mean
}).sort_values(by='importance', ascending=False)

# Save feature importance dataset
importance_df.to_csv('edupredict_assets/feature_importance.csv', index=False)
print("Top 5 predictive features:")
print(importance_df.head(5))

